import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'dist');
if (!fs.existsSync(path.join(source, 'index.html'))) throw new Error('Run npm run build before syncing Android assets.');
const target = path.join(root, 'android/app/src/main/assets/web');
fs.rmSync(target, { recursive: true, force: true });
fs.mkdirSync(target, { recursive: true });
fs.cpSync(source, target, { recursive: true });
console.log('Offline web bundle copied into the Android application assets.');
